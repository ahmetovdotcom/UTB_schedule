ROOM_TYPES = {LEC, CLS, PC, LAB, SPEC, OTHER}


@dataclass(frozen=True)
class RoomRow:
    building: str
    number: str
    room_type: str
    department: str
    capacity: int
    floor: int
    title: str


def floor_of(number: str) -> int:
    """'413' -> 4, '108' -> 1, '2/10а' -> 2, '19' -> 1."""
    if "/" in number:
        return int(number.split("/", 1)[0])
    digits = re.match(r"\d+", number)
    if not digits or len(digits.group()) < 3:
        return 1
    return int(digits.group()[:-2])


def build_plan(include_extra: bool) -> list[RoomRow]:
    """Flatten and validate the data; raises ValueError on inconsistencies."""
    buildings = dict(BUILDINGS)
    if include_extra:
        buildings.update(EXTRA_BUILDINGS)

    rows: list[RoomRow] = []
    for building, rooms in buildings.items():
        seen: set[str] = set()
        for number, room_type, department, capacity, title in rooms:
            if number in seen:
                raise ValueError(f"{building}: аудитория {number} встречается дважды")
            seen.add(number)
            if room_type not in ROOM_TYPES:
                raise ValueError(f"{building}/{number}: неизвестный тип {room_type}")
            if capacity <= 0:
                raise ValueError(f"{building}/{number}: нет мест — перенесите в SKIPPED")
            rows.append(
                RoomRow(building, number, room_type, department, capacity, floor_of(number), title)
            )
    return rows


async def apply(rows: list[RoomRow], dry_run: bool) -> None:
    from sqlalchemy import select

    from database.models import Building, Department, Room, async_session, init_db

    await init_db()  # создаёт таблицы и мигрирует старую БД

    stats = {"departments": 0, "buildings": 0, "rooms_added": 0, "rooms_updated": 0, "rooms_same": 0}
    async with async_session() as session:
        departments = {d.name: d for d in (await session.execute(select(Department))).scalars()}
        for name in sorted({r.department for r in rows}):
            if name not in departments:
                departments[name] = Department(name=name)
                session.add(departments[name])
                stats["departments"] += 1

        buildings = {b.name: b for b in (await session.execute(select(Building))).scalars()}
        for name in dict.fromkeys(r.building for r in rows):
            if name not in buildings:
                buildings[name] = Building(name=name)
                session.add(buildings[name])
                stats["buildings"] += 1
        await session.flush()  # ids for new departments/buildings

        building_ids = [buildings[name].id for name in dict.fromkeys(r.building for r in rows)]
        existing = {
            (room.building_id, room.number): room
            for room in (
                await session.execute(select(Room).where(Room.building_id.in_(building_ids)))
            ).scalars()
        }

        for row in rows:
            values = {
                "capacity": row.capacity,
                "room_type": row.room_type,
                "department_id": departments[row.department].id,
                "floor": row.floor,
            }
            building_id = buildings[row.building].id
            room = existing.get((building_id, row.number))
            if room is None:
                session.add(Room(building_id=building_id, number=row.number, **values))
                stats["rooms_added"] += 1
            elif any(getattr(room, k) != v for k, v in values.items()):
                for k, v in values.items():
                    setattr(room, k, v)
                stats["rooms_updated"] += 1
            else:
                stats["rooms_same"] += 1

        if dry_run:
            await session.rollback()
        else:
            await session.commit()

    prefix = "[dry-run] было бы: " if dry_run else ""
    print(
        f"{prefix}кафедр добавлено {stats['departments']}, корпусов {stats['buildings']}, "
        f"аудиторий добавлено {stats['rooms_added']}, обновлено {stats['rooms_updated']}, "
        f"без изменений {stats['rooms_same']}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Импорт аудиторного фонда КазУТБ в БД")
    parser.add_argument("--all", action="store_true", help="также пр. Республики 54/2 и Дом студентов")
    parser.add_argument("--dry-run", action="store_true", help="ничего не записывать")
    args = parser.parse_args()

    rows = build_plan(include_extra=args.all)
    by_building: dict[str, int] = {}
    for r in rows:
        by_building[r.building] = by_building.get(r.building, 0) + 1
    print("К импорту:", ", ".join(f"{b} — {n}" for b, n in by_building.items()))
    skipped = [s for s in SKIPPED if s[0] in by_building]
    if skipped:
        print("Пропущены (нет посадочных мест):", ", ".join(f"{b} {n}" for b, n, _ in skipped))

    asyncio.run(apply(rows, dry_run=args.dry_run))


if __name__ == "__main__":
    main()
