def build_plan() -> list[tuple[str, int, str, int]]:
    """Validate the data; raises ValueError on inconsistencies."""
    duplicates = [k for k, n in Counter((c, course) for _, course, c, _ in GROUPS).items() if n > 1]
    if duplicates:
        raise ValueError(f"Повторяются группы (код, курс): {duplicates}")
    for faculty, course, code, students in GROUPS:
        if not 1 <= course <= 5:
            raise ValueError(f"{code}: странный курс {course}")
        if students <= 0:
            raise ValueError(f"{code}: нет студентов")
    return GROUPS


async def apply(groups: list[tuple[str, int, str, int]], dry_run: bool) -> None:
    from sqlalchemy import func, select

    from database.models import Room, StudentGroup, async_session, init_db

    await init_db()  # создаёт таблицы и мигрирует старую БД

    added = updated = same = 0
    async with async_session() as session:
        existing = {
            (g.code, g.course): g
            for g in (await session.execute(select(StudentGroup))).scalars()
        }
        for _, course, code, students in groups:
            group = existing.get((code, course))
            if group is None:
                session.add(StudentGroup(code=code, course=course, students_count=students))
                added += 1
            elif group.students_count != students:
                group.students_count = students
                updated += 1
            else:
                same += 1

        max_capacity = await session.scalar(
            select(func.max(Room.capacity)).where(Room.room_type != "other")
        )

        if dry_run:
            await session.rollback()
        else:
            await session.commit()

    prefix = "[dry-run] было бы: " if dry_run else ""
    print(f"{prefix}групп добавлено {added}, обновлено {updated}, без изменений {same}")

    if max_capacity:
        too_big = [(code, course, n) for _, course, code, n in groups if n > max_capacity]
        if too_big:
            print(
                f"\nВнимание: {len(too_big)} групп больше самой большой аудитории ({max_capacity} мест) — "
                "их пары не встанут ни в одну аудиторию целиком, скорее всего их нужно делить на подгруппы:"
            )
            for code, course, n in sorted(too_big, key=lambda g: -g[2]):
                print(f"  {code} ({course} курс) — {n}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Импорт учебных групп КазУТБ в БД")
    parser.add_argument("--dry-run", action="store_true", help="ничего не записывать")
    args = parser.parse_args()

    groups = build_plan()
    by_faculty = Counter(f for f, *_ in groups)
    students = sum(n for *_, n in groups)
    print(
        f"К импорту: {len(groups)} групп, {students} студентов ("
        + ", ".join(f"{f} — {n}" for f, n in by_faculty.items())
        + ")"
    )
    same_code = sorted({c for c, n in Counter(code for _, _, code, _ in groups).items() if n > 1})
    if same_code:
        print("Один и тот же код на разных курсах (проверьте в деканате):", ", ".join(same_code))

    asyncio.run(apply(groups, dry_run=args.dry_run))


if __name__ == "__main__":
    main()
